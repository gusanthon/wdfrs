use proc_macro2::TokenStream as TokenStream2;
use quote::{format_ident, quote};
use syn::{
    parse::{Parse, ParseStream},
    Token,
};
use syn::{Ident, LitInt};

pub(crate) struct RTypeInput {
    pub name: Ident,
    pub n_ports: usize,
}

impl Parse for RTypeInput {
    fn parse(input: ParseStream) -> syn::Result<Self> {
        let name: Ident = input.parse()?;
        input.parse::<Token![,]>()?;
        let n_lit: LitInt = input.parse()?;
        let n_ports: usize = n_lit.base10_parse()?;
        if n_ports < 3 {
            return Err(syn::Error::new(
                n_lit.span(),
                "define_rtype requires at least 3 ports (1 parent + 2 children minimum)",
            ));
        }
        Ok(Self { name, n_ports })
    }
}

pub(crate) fn gen_rtype(name: &Ident, n_ports: usize) -> TokenStream2 {
    let n_children = n_ports - 1; // one port is the parent
    let n_sq = n_ports * n_ports;

    let fields: Vec<Ident> = (1..=n_children).map(|i| format_ident!("p{}", i)).collect();
    let tparams: Vec<Ident> = (1..=n_children).map(|i| format_ident!("P{}", i)).collect();

    let np = proc_macro2::Literal::usize_unsuffixed(n_ports);
    let nsq = proc_macro2::Literal::usize_unsuffixed(n_sq);
    let nc = proc_macro2::Literal::usize_unsuffixed(n_children);

    // get_reflected_wave: collect a wave per child, skipping up_port
    let get_reflected = fields.iter().map(|f| {
        quote! {
            {
                let wave = self.#f.get_reflected_wave();
                if _port == self.up_port { _port += 1; }
                unsafe { (*self.a_waves.get())[_port] = wave; }
                _port += 1;
            }
        }
    });

    // set_incident_wave: push b wave to each child, skipping up_port
    let set_incident = fields.iter().map(|f| {
        quote! {
            {
                if _port == self.up_port { _port += 1; }
                let wave = unsafe { (*self.b_waves.get())[_port] };
                self.#f.set_incident_wave(wave);
                _port += 1;
            }
        }
    });

    let f1 = &fields[0];
    let rest = &fields[1..];
    let n_rest_lit = proc_macro2::Literal::usize_unsuffixed(rest.len());
    let rest_prints = rest.iter().enumerate().map(|(i, f)| {
        let idx = proc_macro2::Literal::usize_unsuffixed(i + 1);
        quote! { self.#f.print_tree(prefix, #idx == child_count); }
    });

    quote! {
        /// An R-type adaptor generated by [`define_rtype`].
        pub struct #name<T, #(#tparams),*>
        where
            T: WDFloat,
            #(#tparams: WDF<T>),*
        {
            params:         ::core::cell::UnsafeCell<WDFParams<T>>,
            scatter_mat:    ::core::cell::UnsafeCell<[T; #nsq]>,
            a_waves:        ::core::cell::UnsafeCell<[T; #np]>,
            b_waves:        ::core::cell::UnsafeCell<[T; #np]>,
            #(pub #fields:  #tparams,)*
            up_port:        usize,
            impedance_calc: fn(&Self) -> T,
        }

        impl<T, #(#tparams),*> #name<T, #(#tparams),*>
        where
            T: WDFloat,
            #(#tparams: WDF<T>),*
        {
            /// Creates a new R-type adaptor.
            ///
            /// * `up_port` – which of the N ports connects upward to the parent (0-indexed).
            /// * `impedance_calc` – returns this adaptor's port impedance given `&Self`.
            ///
            /// # Panics
            /// Panics if `up_port >= N`.
            #[allow(clippy::too_many_arguments)]
            pub fn new(
                #(#fields: #tparams,)*
                up_port: usize,
                impedance_calc: fn(&Self) -> T,
            ) -> Self {
                assert!(up_port < #np, "up_port out of range");
                let s = Self {
                    params:      ::core::cell::UnsafeCell::new(WDFParams::default()),
                    scatter_mat: ::core::cell::UnsafeCell::new([T::zero(); #nsq]),
                    a_waves:     ::core::cell::UnsafeCell::new([T::zero(); #np]),
                    b_waves:     ::core::cell::UnsafeCell::new([T::zero(); #np]),
                    #(#fields,)*
                    up_port,
                    impedance_calc,
                };
                s.calc_impedance();
                s
            }

            /// Returns the port impedance of each child (all ports except the parent).
            pub fn get_port_impedances(&self) -> [T; #nc] {
                [#(self.#fields.params().rp),*]
            }

            /// Sets the N×N scattering matrix (row-major, `b = S·a`).
            pub fn set_scattering_matrix(&self, mat: [T; #nsq]) {
                unsafe { *self.scatter_mat.get() = mat; }
            }

            fn scatter(&self) {
                let n = #np;
                let s = unsafe { &*self.scatter_mat.get() };
                let a = unsafe { &*self.a_waves.get() };
                let b = unsafe { &mut *self.b_waves.get() };
                for row in 0..n {
                    let mut sum = T::zero();
                    let off = row * n;
                    for col in 0..n {
                        unsafe { sum = sum + *s.get_unchecked(off + col) * *a.get_unchecked(col); }
                    }
                    unsafe { *b.get_unchecked_mut(row) = sum; }
                }
            }
        }

        impl<T, #(#tparams),*> WDF<T> for #name<T, #(#tparams),*>
        where
            T: WDFloat,
            #(#tparams: WDF<T>),*
        {
            #[inline(always)]
            fn params_ptr(&self) -> *mut WDFParams<T> {
                self.params.get()
            }

            fn calc_impedance(&self) {
                #(self.#fields.calc_impedance();)*
                let rp = (self.impedance_calc)(self);
                let p = self.params_mut();
                p.rp = rp;
                p.g = T::one() / rp;
            }

            fn get_reflected_wave(&self) -> T {
                let mut _port = 0usize;
                #(#get_reflected)*
                let b_val = unsafe { (*self.b_waves.get())[self.up_port] };
                self.params_mut().b = b_val;
                b_val
            }

            fn set_incident_wave(&self, a: T) {
                unsafe {
                    (*self.params.get()).a = a;
                    (*self.a_waves.get())[self.up_port] = a;
                }
                self.scatter();
                let mut _port = 0usize;
                #(#set_incident)*
            }

            fn reset(&self) {
                unsafe {
                    (*self.params.get()).reset();
                    *self.a_waves.get() = [T::zero(); #np];
                    *self.b_waves.get() = [T::zero(); #np];
                }
                #(self.#fields.reset();)*
            }

            fn set_sample_rate(&self, fs: T) {
                self.for_each_child(&mut |child| { child.set_sample_rate(fs); });
                self.calc_impedance();
            }

            fn for_each_child(&self, f: &mut dyn FnMut(&dyn WDF<T>)) {
                #(f(&self.#fields);)*
            }

            fn find_by_id_ptr(&self, id: &str) -> ::core::option::Option<::core::ptr::NonNull<dyn ::core::any::Any>> {
                if self.params().id == Some(id) {
                    let raw = self as *const Self as *mut Self as *mut dyn ::core::any::Any;
                    return ::core::ptr::NonNull::new(raw);
                }
                #(if let Some(found) = self.#fields.find_by_id_ptr(id) { return Some(found); })*
                None
            }

            fn recurse_print(&self, prefix: &str) {
                let child_count = #n_rest_lit;
                self.#f1.print_tree(prefix, child_count == 0);
                #(#rest_prints)*
            }
        }
    }
}

pub(crate) fn gen_root_rtype(name: &Ident, n_ports: usize) -> TokenStream2 {
    let n_sq = n_ports * n_ports;

    let fields: Vec<Ident> = (1..=n_ports).map(|i| format_ident!("p{}", i)).collect();
    let tparams: Vec<Ident> = (1..=n_ports).map(|i| format_ident!("P{}", i)).collect();
    let tp1 = &tparams[0]; // used for `type Next = #tp1`

    let np = proc_macro2::Literal::usize_unsuffixed(n_ports);
    let nsq = proc_macro2::Literal::usize_unsuffixed(n_sq);

    let f1 = &fields[0];
    let rest = &fields[1..];
    let n_rest_lit = proc_macro2::Literal::usize_unsuffixed(rest.len());
    let rest_prints = rest.iter().enumerate().map(|(i, f)| {
        let idx = proc_macro2::Literal::usize_unsuffixed(i + 1);
        quote! { self.#f.print_tree(prefix, #idx == child_count); }
    });

    let compute_ports = fields.iter().map(|f| {
        quote! {
            {
                let b_val = unsafe { (*self.b_waves.get())[_port] };
                self.#f.set_incident_wave(b_val);
                unsafe { (*self.a_waves.get())[_port] = self.#f.get_reflected_wave(); }
                _port += 1;
            }
        }
    });

    quote! {
        /// A root R-type adaptor generated by [`define_root_rtype`].
        pub struct #name<T, #(#tparams),*>
        where
            T: WDFloat,
            #(#tparams: WDF<T>),*
        {
            params:      ::core::cell::UnsafeCell<WDFParams<T>>,
            scatter_mat: ::core::cell::UnsafeCell<[T; #nsq]>,
            a_waves:     ::core::cell::UnsafeCell<[T; #np]>,
            b_waves:     ::core::cell::UnsafeCell<[T; #np]>,
            #(pub #fields: #tparams,)*
            impedance_calc: fn(&Self),
        }

        impl<T, #(#tparams),*> #name<T, #(#tparams),*>
        where
            T: WDFloat,
            #(#tparams: WDF<T>),*
        {
            /// Creates a new root R-type adaptor.
            ///
            /// `impedance_calc` receives `&Self` and is responsible for computing
            /// port impedances and calling `set_scattering_matrix`.
            #[allow(clippy::too_many_arguments)]
            pub fn new(
                #(#fields: #tparams,)*
                impedance_calc: fn(&Self),
            ) -> Self {
                let s = Self {
                    params:      ::core::cell::UnsafeCell::new(WDFParams::default()),
                    scatter_mat: ::core::cell::UnsafeCell::new([T::zero(); #nsq]),
                    a_waves:     ::core::cell::UnsafeCell::new([T::zero(); #np]),
                    b_waves:     ::core::cell::UnsafeCell::new([T::zero(); #np]),
                    #(#fields,)*
                    impedance_calc,
                };
                s.calc_impedance();
                s
            }

            /// Returns the port impedances of all N children.
            pub fn get_port_impedances(&self) -> [T; #np] {
                [#(self.#fields.params().rp),*]
            }

            /// Sets the N×N scattering matrix (row-major, `b = S·a`).
            pub fn set_scattering_matrix(&self, mat: [T; #nsq]) {
                unsafe { *self.scatter_mat.get() = mat; }
            }

            fn scatter(&self) {
                let n = #np;
                let s = unsafe { &*self.scatter_mat.get() };
                let a = unsafe { &*self.a_waves.get() };
                let b = unsafe { &mut *self.b_waves.get() };
                for row in 0..n {
                    let mut sum = T::zero();
                    let off = row * n;
                    for col in 0..n {
                        unsafe { sum = sum + *s.get_unchecked(off + col) * *a.get_unchecked(col); }
                    }
                    unsafe { *b.get_unchecked_mut(row) = sum; }
                }
            }
        }

        impl<T, #(#tparams),*> WDF<T> for #name<T, #(#tparams),*>
        where
            T: WDFloat,
            #(#tparams: WDF<T>),*
        {
            fn params_ptr(&self) -> *mut WDFParams<T> {
                self.params.get()
            }

            fn calc_impedance(&self) {
                #(self.#fields.calc_impedance();)*
                (self.impedance_calc)(self);
            }

            fn get_reflected_wave(&self) -> T {
                let name = stringify!(#name);
                unimplemented!("cannot call `{name}::get_reflected_wave()` — use `compute()` instead")
            }

            fn set_incident_wave(&self, _a: T) {
                let name = stringify!(#name);
                unimplemented!("cannot call `{name}::set_incident_wave()` — use `compute()` instead")
            }

            fn reset(&self) {
                unsafe {
                    (*self.params.get()).reset();
                    *self.a_waves.get() = [T::zero(); #np];
                    *self.b_waves.get() = [T::zero(); #np];
                }
                #(self.#fields.reset();)*
            }

            fn set_sample_rate(&self, fs: T) {
                self.for_each_child(&mut |child| { child.set_sample_rate(fs); });
                self.calc_impedance();
            }

            fn for_each_child(&self, f: &mut dyn FnMut(&dyn WDF<T>)) {
                #(f(&self.#fields);)*
            }

            fn find_by_id_ptr(&self, id: &str) -> ::core::option::Option<::core::ptr::NonNull<dyn ::core::any::Any>> {
                if self.params().id == Some(id) {
                    let raw = self as *const Self as *mut Self as *mut dyn ::core::any::Any;
                    return ::core::ptr::NonNull::new(raw);
                }
                #(if let Some(found) = self.#fields.find_by_id_ptr(id) { return Some(found); })*
                None
            }

            fn recurse_print(&self, prefix: &str) {
                let child_count = #n_rest_lit;
                self.#f1.print_tree(prefix, child_count == 0);
                #(#rest_prints)*
            }
        }

        impl<T, #(#tparams),*> RootWDF<T> for #name<T, #(#tparams),*>
        where
            T: WDFloat,
            #(#tparams: WDF<T>),*
        {
            type Next = #tp1; // uses the Ident from tparams[0], avoiding hygiene mismatch

            fn next(&self) -> &Self::Next {
                let name = stringify!(#name);
                unimplemented!("`RootWDF::next()` is not supported for multi-port `{name}` — use `compute()`");
            }

            #[inline(always)]
            fn compute(&self) {
                self.scatter();
                let mut _port = 0usize;
                #(#compute_ports)*
            }

            fn reset_tree(&self) where Self: Sized { self.reset(); }

            fn set_tree_sample_rate(&self, fs: T) {
                self.for_each_tree(&mut |wdf| { wdf.set_sample_rate(fs); });
                self.calc_impedance();
            }

            fn for_each_tree(&self, f: &mut dyn FnMut(&dyn WDF<T>)) where Self: Sized {
                f(self);
                self.walk_children(f);
            }
        }
    }
}
